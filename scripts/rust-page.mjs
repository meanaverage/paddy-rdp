// Build pure Rust page cores; generated modules belong to the copied frontend, never the source tree.
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { pageOptions, pageBuilds } from './rust-page-options.mjs'
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)))
const { output, offline, modules } = pageOptions(process.argv.slice(2), path.join(root, '.build/tabby/tabby-itabby/src/rust'))
const builds = pageBuilds(root, modules)
const toolchain = /channel\s*=\s*"([^"]+)"/.exec(fs.readFileSync(path.join(root, 'rust-toolchain.toml'), 'utf8'))[1]
process.env.RUSTUP_TOOLCHAIN = toolchain
try { execFileSync('rustup', ['run', toolchain, 'rustc', '--version'], { stdio: 'ignore' }) }
catch (error) {
    if (offline) throw error
    execFileSync('rustup', ['toolchain', 'install', toolchain, '--profile', 'minimal'], { cwd: root, stdio: 'inherit' })
}
const installed = execFileSync('rustup', ['target', 'list', '--installed'], { cwd: root, encoding: 'utf8' })
if (!installed.split('\n').includes('wasm32-unknown-unknown')) {
    if (offline) throw new Error(`Install the WebAssembly target first: rustup target add --toolchain ${toolchain} wasm32-unknown-unknown`)
    execFileSync('rustup', ['target', 'add', 'wasm32-unknown-unknown'], { cwd: root, stdio: 'inherit' })
}
const target = path.resolve(root, process.env.CARGO_TARGET_DIR ?? 'src-tauri/target/page-core')
fs.mkdirSync(output, { recursive: true })
for (const { name, dir, crate, module } of builds) {
    // cdylib+rlib artifacts have unhashed names. Keep a page's exports separate
    // from the same crate built as another page's library with different features.
    const crateTarget = path.join(target, name)
    execFileSync('cargo', ['build', '--release', '--locked', '--target', 'wasm32-unknown-unknown', '--manifest-path', path.join(dir, 'Cargo.toml'), ...offline ? ['--offline'] : []], {
        cwd: root, stdio: 'inherit', env: { ...process.env, CARGO_TARGET_DIR: crateTarget, RUSTFLAGS: '-C link-arg=--max-memory=134217728' },
    })
    const bytes = fs.readFileSync(path.join(crateTarget, 'wasm32-unknown-unknown/release', `${crate}.wasm`))
    fs.writeFileSync(path.join(output, `${module}.data.ts`), `// Generated by scripts/rust-page.mjs.\nexport const WASM = ${JSON.stringify(bytes.toString('base64'))}\n`)
    console.log(`${module}: ${bytes.length} bytes of WebAssembly`)
}
